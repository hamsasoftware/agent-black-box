from __future__ import annotations

import json
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

from blackbox.redact import Redactor


def load_runs(root: Path) -> list[dict[str, Any]]:
    runs = []
    for path in sorted((root / "runs").glob("*/run.json")):
        try:
            data = json.loads(path.read_text())
        except (OSError, json.JSONDecodeError):
            continue
        if isinstance(data, dict) and data.get("run_id"):
            runs.append(data)
    return sorted(runs, key=lambda r: r["run_id"])


def index_row(r: dict[str, Any]) -> dict[str, Any]:
    grade = r.get("grade") or {}
    return {
        "run_id": r["run_id"], "task_id": r.get("task_id"), "variant": r.get("variant"), "model": r.get("model"),
        "agent_id": r.get("agent_id"), "agent_name": r.get("agent_name"), "started_at": r.get("started_at"),
        "passed": bool(grade.get("passed")), "score": grade.get("score"), "cost_usd": r.get("cost_usd"),
        "input_tokens": r.get("input_tokens"), "output_tokens": r.get("output_tokens"),
        "cache_read_tokens": r.get("cache_read_tokens"), "cache_creation_tokens": r.get("cache_creation_tokens"),
        "turns": r.get("turns"), "duration_ms": r.get("duration_ms"), "stop_reason": r.get("stop_reason"),
        "behaviours": sorted(b["id"] for b in r.get("behaviours") or []),
    }


def build_index(root: Path, redactor: Redactor) -> Path:
    path = root / "runs" / "index.jsonl"
    path.parent.mkdir(parents=True, exist_ok=True)
    rows = [index_row(r) for r in load_runs(root)]
    path.write_text("".join(json.dumps(redactor.obj(row), ensure_ascii=False) + "\n" for row in rows))
    return path


def _mean(values: list[Any]) -> float | None:
    nums = [float(v) for v in values if isinstance(v, (int, float))]
    return sum(nums) / len(nums) if nums else None


def _fmt(value: float | None, pattern: str) -> str:
    return "n/a" if value is None else pattern.format(value)


def render(rows: list[dict[str, Any]]) -> str:
    groups: dict[tuple[str, str], list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        groups[(str(row.get("task_id")), str(row.get("variant")))].append(row)
    lines = [
        "# Results",
        "",
        "Generated by `python -m blackbox report` from `runs/index.jsonl`. Do not edit by hand.",
        "",
        f"Runs: {len(rows)}.",
        "",
        "| Task | Variant | Runs | Pass rate | Mean score | Mean cost (USD) | Mean input tokens | Mean output tokens | Mean turns | Behaviours |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for (task, variant), group in sorted(groups.items()):
        passes = sum(1 for r in group if r.get("passed"))
        counts = Counter(b for r in group for b in r.get("behaviours") or [])
        behaviours = ", ".join(f"{b} ({n})" for b, n in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))) or "none"
        lines.append(
            f"| {task} | {variant} | {len(group)} | {passes}/{len(group)} ({100 * passes / len(group):.0f}%) | "
            f"{_fmt(_mean([r.get('score') for r in group]), '{:.2f}')} | "
            f"{_fmt(_mean([r.get('cost_usd') for r in group]), '{:.4f}')} | "
            f"{_fmt(_mean([r.get('input_tokens') for r in group]), '{:.0f}')} | "
            f"{_fmt(_mean([r.get('output_tokens') for r in group]), '{:.0f}')} | "
            f"{_fmt(_mean([r.get('turns') for r in group]), '{:.1f}')} | {behaviours} |")
    if not groups:
        lines.append("| none | | 0 | | | | | | | |")
    lines += ["", "Input tokens exclude cache reads and cache writes; see each run.json for those.", ""]
    return "\n".join(lines)


def build_report(root: Path, redactor: Redactor) -> Path:
    index = root / "runs" / "index.jsonl"
    if not index.is_file():
        build_index(root, redactor)
    rows = [json.loads(line) for line in index.read_text().splitlines() if line.strip()]
    out = root / "docs" / "results.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(redactor.text(render(rows)))
    return out
